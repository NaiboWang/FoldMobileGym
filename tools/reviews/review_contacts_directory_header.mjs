import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { openPilotApp } from '../browser-automation/pilot_app_navigation.mjs';
import { resolveBrowserExecutable } from '../browser-automation/browser.mjs';
const root = path.resolve(import.meta.dirname, '../..');
const frontend = fs.existsSync(path.join(root, 'foldmobilegym/package.json')) ? 'foldmobilegym' : 'mobilegym';
const require = createRequire(path.join(root, frontend, 'package.json'));
const url = new URL(process.env.FOLDAGENT_REVIEW_URL || 'http://127.0.0.1:3371/');
assert.ok(url.protocol === 'http:' && ['127.0.0.1', 'localhost'].includes(url.hostname) && !url.username && !url.password);
const browser = await require('puppeteer').launch({headless:true, executablePath:resolveBrowserExecutable()});
const context = await browser.createBrowserContext(), p = await context.newPage(), errors=[];
p.on('pageerror', e => errors.push(String(e)));
try {
 await p.setViewport({width:1440,height:1100}); await p.goto(url.href);
 await p.waitForFunction(() => window.__OS__ && window.__FOLDAGENT__);
 await p.evaluate(() => window.__FOLDAGENT__.setPosture('unfolded'));
 await openPilotApp(p,'contacts','/contact/c_alice');
 const a='[data-app-id="contacts"]';
 await p.waitForSelector(`${a} .contacts-directory-header[data-search-active="false"]`,{visible:true});
 assert.ok(await p.$(`${a} .contacts-page-title`));
 assert.match(await p.$eval(`${a} .contacts-page-title`, e => e.parentElement.textContent), /\d+/);
 assert.equal(await p.$(`${a} .contacts-directory-search-scrim`),null);
 await p.click(`${a} .contacts-directory-search`);
 await p.waitForSelector(`${a} .contacts-directory-header[data-search-active="true"]`);
 assert.equal(await p.$(`${a} .contacts-page-title`),null);
 assert.ok(await p.$(`${a} .contacts-directory-search-scrim`));
 assert.equal(await p.$eval(`${a} .contacts-directory-search`, e=>document.activeElement===e),true);
 await p.type(`${a} .contacts-directory-search`,'Alice');
 await p.waitForFunction(() => new URL(window.__OS__.getAppRoute('contacts').path,'http://local').searchParams.get('q')==='Alice');
 assert.equal(await p.$(`${a} .contacts-directory-search-scrim`),null);
 assert.ok(await p.$(`${a} .contacts-detail-pane`));
 await p.evaluate(() => window.__OS__.keyboard.hide());
 await p.click(`${a} .contacts-directory-header button`);
 await p.waitForSelector(`${a} .contacts-directory-header[data-search-active="false"]`);
 assert.equal(await p.$eval(`${a} .contacts-directory-search`,e=>e.value),'');
 assert.equal(await p.evaluate(()=>new URL(window.__OS__.getAppRoute('contacts').path,'http://local').pathname),'/contact/c_alice');
 assert.deepEqual(errors,[]); console.log('PASS expanded directory header, focus, scrim, query and button back');
} finally { await context.close(); await browser.close(); }
