import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { openPilotApp } from '../browser-automation/pilot_app_navigation.mjs';
import { resolveBrowserExecutable } from '../browser-automation/browser.mjs';
const root=path.resolve(import.meta.dirname,'../..');
const frontend=fs.existsSync(path.join(root,'foldmobilegym/package.json'))?'foldmobilegym':'mobilegym';
const require=createRequire(path.join(root,frontend,'package.json'));
const url=new URL(process.env.FOLDAGENT_REVIEW_URL||'http://127.0.0.1:3376/');
assert.ok(url.protocol==='http:'&&['127.0.0.1','localhost'].includes(url.hostname)&&!url.username&&!url.password);
const browser=await require('puppeteer').launch({headless:true,executablePath:resolveBrowserExecutable()});
const context=await browser.createBrowserContext(),p=await context.newPage(),errors=[];
p.on('pageerror',e=>errors.push(String(e)));
const app='[data-app-id="contacts"]';
try {
 await p.setViewport({width:1440,height:1100}); await p.goto(url.href);
 await p.waitForFunction(()=>window.__OS__&&window.__FOLDAGENT__);
 await p.evaluate(()=>window.__FOLDAGENT__.setPosture('unfolded'));
 await openPilotApp(p,'contacts','/contact/c_alice');
 await p.evaluate(()=>window.__OS__.content.insert('content://contacts/contacts',{displayName:'123456789',phones:[],sectionKey:'#'}));
 await p.waitForFunction(app=>[...document.querySelectorAll(`${app} [data-contact-section]`)].some(e=>e.dataset.contactSection==='#'),{},app);
 const sections=await p.$$eval(`${app} [data-contact-section]`,es=>es.map(e=>e.dataset.contactSection));
 assert.equal(sections[0],'#');
 const index=await p.$$eval(`${app} .contacts-alphabet-index [data-section]`,es=>es.map(e=>e.textContent));
 assert.deepEqual(index,['#',...'ABCDEFGHIJKLMNOPQRSTUVWXYZ']);
 const ib=await p.$eval(`${app} .contacts-alphabet-index`,e=>{const r=e.getBoundingClientRect(),p=e.parentElement.getBoundingClientRect();return {top:r.top,bottom:r.bottom,ptop:p.top,pbottom:p.bottom};});
 assert.ok(ib.top>=ib.ptop-1&&ib.bottom<=ib.pbottom+1,'index stays inside list area');
 const letters=await p.$$eval(`${app} .contacts-alphabet-index [data-section]`, es => es.map(e => { const r=e.getBoundingClientRect(); return {top:r.top,bottom:r.bottom}; }));
 assert.ok(letters.every(r=>r.top>=ib.top-1&&r.bottom<=ib.bottom+1),'every letter stays inside index');
 const b=await p.$eval(`${app} .contacts-alphabet-index [data-section="B"]`, e=>{const r=e.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2};});
 await p.mouse.click(b.x,b.y);
 await p.waitForFunction(app=>document.querySelector(`${app} .contacts-alphabet-index`)?.getAttribute('aria-valuetext')==='B',{},app);
 await new Promise(resolve=>setTimeout(resolve,600));
 const moved=await p.$eval(`${app} [data-scroll-container="directory"]`,e=>e.scrollTop);
 assert.ok(moved>0,'index scrolls the contact list');
 await p.focus(`${app} .contacts-alphabet-index`); await p.keyboard.press('Home');
 await p.waitForFunction(app=>document.querySelector(`${app} .contacts-alphabet-index`)?.getAttribute('aria-valuetext')==='#',{},app);
 await new Promise(resolve=>setTimeout(resolve,600));
 await p.keyboard.press('ArrowDown');
 await p.waitForFunction(app=>document.querySelector(`${app} .contacts-alphabet-index`)?.getAttribute('aria-valuetext')==='A',{},app);
 await p.click(`${app} .contacts-directory-search`);
 await p.waitForSelector(`${app} .contacts-directory-search-scrim`,{visible:true});
 await p.type(`${app} .contacts-directory-search`,'Alice');
 await p.waitForSelector(`${app} .contacts-alphabet-index`,{hidden:true});
 await p.evaluate(()=>window.__FOLDAGENT__.setPosture('folded'));
 await openPilotApp(p,'contacts','/contacts');
 await p.waitForSelector(`${app} .contacts-alphabet-index`,{visible:true});
 const folded=await p.$$eval(`${app} .contacts-alphabet-index [data-section]`,es=>es.map(e=>e.textContent));
 assert.deepEqual(folded,['#',...'ABCDEFGHIJKLMNOPQRSTUVWXYZ']);
 assert.deepEqual(errors,[]); console.log('PASS numeric section, full index, bounded letters, pointer and keyboard selection, search, folded layout');
} finally {await context.close();await browser.close();}
